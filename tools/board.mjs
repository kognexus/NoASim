#!/usr/bin/env node
/**
 * Builds docs/tickets/BOARD.md from the front matter of the ticket files.
 *
 *   node tools/board.mjs           rewrite BOARD.md
 *   node tools/board.mjs --check   fail if BOARD.md is stale or a ticket is malformed
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const TICKET_DIR = "docs/tickets";
const BOARD_PATH = join(TICKET_DIR, "BOARD.md");
const STATUSES = ["todo", "in-progress", "done"];

/** Parses the YAML-like front matter used by the ticket files (flat keys only). */
function parseFrontMatter(path) {
  const match = readFileSync(path, "utf8").match(/^---\n([\s\S]*?)\n---\n/);
  if (!match) throw new Error(`${path}: missing front matter`);
  const fields = Object.fromEntries(
    match[1].split("\n").map((line) => {
      const i = line.indexOf(":");
      return [line.slice(0, i).trim(), line.slice(i + 1).trim()];
    }),
  );
  if (!STATUSES.includes(fields.status)) {
    throw new Error(`${path}: status must be one of ${STATUSES.join(", ")}`);
  }
  return fields;
}

function renderBoard(tickets) {
  const done = tickets.filter((t) => t.status === "done").length;
  const rows = tickets.map(
    (t) =>
      `| [${t.id}](${t.id}.md) | ${t.title} | ${t.status} | ${t.depends.replace(/[[\]]/g, "")} |`,
  );
  return [
    "# Ticket board",
    "",
    "*Generated by `npm run board` from the ticket files. Do not edit by hand.*",
    "",
    `${done} of ${tickets.length} tickets done.`,
    "",
    "| Ticket | Title | Status | Depends on |",
    "|---|---|---|---|",
    ...rows,
    "",
  ].join("\n");
}

const tickets = readdirSync(TICKET_DIR)
  .filter((name) => /^NX-\d+\.md$/.test(name))
  .sort()
  .map((name) => parseFrontMatter(join(TICKET_DIR, name)));
const board = renderBoard(tickets);

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(BOARD_PATH, "utf8");
  } catch {
    // A missing board is reported as stale below.
  }
  if (current !== board) {
    console.error(`${BOARD_PATH} is stale; run \`npm run board\`.`);
    process.exit(1);
  }
} else {
  writeFileSync(BOARD_PATH, board);
}
