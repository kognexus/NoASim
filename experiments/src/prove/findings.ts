/**
 * What every hypothesis module returns, and how the proof report is written from it.
 */
import type { Lab } from "../runner.ts";

/** How a measurement compares with its target. */
export type Verdict = "met" | "partly met" | "not met" | "reported";

export interface Finding {
  /** Hypothesis id, e.g. "H1" or "H3b". */
  readonly id: string;
  readonly title: string;
  /** The target, as the plan states it. */
  readonly target: string;
  /** What was measured, one short line. */
  readonly measured: string;
  readonly verdict: Verdict;
  /** Longer explanation and tables, Markdown. */
  readonly detail?: string;
  /** SVG files written for this finding (paths relative to docs/). */
  readonly plots?: readonly string[];
}

export interface ProveContext {
  readonly lab: Lab;
  /** Fewer seeds and trials, for a quick look; the report says so. */
  readonly quick: boolean;
  /** Writes an SVG next to RESULTS.md and returns its path relative to docs/. */
  readonly plot: (name: string, svg: string) => Promise<string>;
  /** Progress line. */
  readonly log: (line: string) => void;
}

const MARK: Record<Verdict, string> = {
  met: "✔ met",
  "partly met": "◐ partly met",
  "not met": "✘ not met",
  reported: "· reported",
};

/** The whole report. */
export function resultsMarkdown(
  findings: readonly Finding[],
  meta: { quick: boolean; seconds: number },
): string {
  const table = [
    "| ID | Hypothesis | Target | Measured | Verdict |",
    "|---|---|---|---|---|",
    ...findings.map(
      (f) => `| ${f.id} | ${f.title} | ${f.target} | ${f.measured} | ${MARK[f.verdict]} |`,
    ),
  ].join("\n");
  const sections = findings
    .map((f) =>
      [
        `## ${f.id}: ${f.title}`,
        "",
        `**Target:** ${f.target}  `,
        `**Measured:** ${f.measured}  `,
        `**Verdict:** ${MARK[f.verdict]}`,
        "",
        f.detail ?? "",
        ...(f.plots ?? []).map((p) => `\n![${f.id}](${p})`),
      ].join("\n"),
    )
    .join("\n\n");
  return [
    "# Results",
    "",
    "Generated by `npm run prove` (`experiments/src/prove.ts`) from the code in this",
    "repository. Every number below is measured in simulation: the nodes are the Rust",
    "joint code compiled to WebAssembly, one instance per joint, each seeing only its own",
    "sensors and the bus. Targets come from the plan (docs/PLAN.md §3). Missed targets are",
    "reported as missed.",
    "",
    meta.quick
      ? "**Quick run**: fewer seeds and trials than the full proof. Do not quote these numbers.\n"
      : "",
    table,
    "",
    sections,
    "",
    `<sub>Proof run took ${Math.round(meta.seconds / 60)} min.</sub>`,
    "",
  ].join("\n");
}
